foreach ($file in $files) {
    foreach ($target in $file.target) {
        $destination = "build/$target"

        New-Item -ItemType Directory -Path (Split-Path $destination) -Force | Out-Null

        Copy-Item "src/$($file.source)" $destination -Force
    }
}

foreach ($version in $versions) {
    $versionPath = "build/$($version.version)"
    $packPath = "$versionPath/pack.mcmeta"

    New-Item -ItemType Directory -Path $versionPath -Force | Out-Null

    $mcmeta = @"
{
    "pack": {
        "pack_format": $($version.pack_format),
        "description": "Transparent GUI"
    }
}
"@

    Set-Content -Path $packPath -Value $mcmeta -Encoding utf8

    # Vytvoření ZIPu
    $zipPath = "result/glass-ui-$($version.version).zip"

    New-Item -ItemType Directory -Path "result" -Force | Out-Null

    Compress-Archive `
        -Path "$versionPath/*" `
        -DestinationPath $zipPath `
        -Force
}

